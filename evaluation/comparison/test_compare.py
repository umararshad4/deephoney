import copy
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

spec = importlib.util.spec_from_file_location('compare', Path(__file__).with_name('compare.py'))
c = importlib.util.module_from_spec(spec); spec.loader.exec_module(c)


class ComparisonTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(); self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        (self.root / 'report.md').write_text('# Answer\nSafe means read-only semantics. [RFC](https://www.rfc-editor.org/rfc/rfc9110.html)\n')
        self.manifest = {'study_id': 'synthetic-selfcheck', 'synthetic': True, 'reference': c.read(Path(__file__).with_name('reference.json')), 'cases': [{'id':'http-methods','question':'Explain safe and idempotent HTTP methods, including side effects and POST.'}], 'runs': []}
        for platform in ('fixture-a', 'fixture-b'):
            for replicate in (1, 2):
                self.manifest['runs'].append({'platform':platform,'case_id':'http-methods','replicate':replicate,'status':'completed' if replicate == 1 else 'failed','artifact':'report.md' if replicate == 1 else None,'sanitized_reviewed':replicate == 1,'elapsed_seconds':0 if platform == 'fixture-a' else None,'observed_cost':0 if platform == 'fixture-a' else None,'currency':'USD' if platform == 'fixture-a' else None,'measurement_notes':'Synthetic measurement; not a provider result.','failure_reason':None if replicate == 1 else 'Synthetic timeout'})

    def prepare(self):
        c.write(self.root / 'manifest.json', self.manifest)
        c.prepare(self.root / 'manifest.json', self.root / 'packet', self.root / 'key.json')
        return c.read(self.root / 'packet/packet.json')

    def grades(self, packet, name):
        rows = []
        for run in packet['runs']:
            if run['status'] != 'completed': continue
            def check(i,j): return {'id':i,'judgment':j,'reason':'Synthetic instrumentation judgment only','source_urls':['https://www.rfc-editor.org/rfc/rfc9110.html']}
            rows.append({'blind_id':run['blind_id'],'citation_checks':[check('claim-1','supported')],'fact_checks':[check('claim-1','correct')],'reference_checks':[check(e['id'],'covered') for e in packet['reference']['evidence']]})
        data = {'study_id':packet['study_id'],'grader':name,'synthetic':True,'independent_human':False,'grades':rows}
        path = self.root / (name + '.json'); c.write(path,data); return path

    def test_end_to_end_failure_denominator_unknown_and_zero(self):
        packet = self.prepare(); paths = [self.grades(packet,n) for n in ('one','two')]
        result = c.summarize(self.root / 'packet/packet.json', self.root / 'key.json', paths, self.root / 'summary.json')
        a,b = result['platforms']; self.assertEqual(a['completion_rate'],.5)
        self.assertEqual(a['observed_cost_by_currency'],{'USD':0}); self.assertEqual(b['cost_unknown_runs'],2)
        self.assertIsNone(b['mean_observed_seconds'])
        for run in result['runs']:
            if run['status']=='completed': self.assertEqual(run['agreement']['reference_checks'],{'unanimous':3,'items':3})
        self.assertTrue(result['synthetic'])
        self.assertEqual((self.root/'key.json').stat().st_mode & 0o777,0o600)
        public = json.dumps(packet)
        self.assertNotIn('fixture-a',public); self.assertNotIn('report.md',public)

    def test_bad_artifact_and_blind_identity(self):
        for path in ('../escape.md','/tmp/report.md'):
            with self.assertRaises(ValueError): c.artifact(self.root,path)
        (self.root/'link.md').symlink_to(self.root/'report.md')
        with self.assertRaises(ValueError): c.artifact(self.root,'link.md')
        (self.root/'report.md').write_text('Generated by FIXTURE-A')
        with self.assertRaises(ValueError): self.prepare()
        self.assertFalse((self.root/'packet').exists())

    def test_missing_duplicate_and_inconsistent_grades(self):
        packet = self.prepare(); path = self.grades(packet,'one'); valid = c.read(path)
        for mutate in (lambda d:d['grades'].pop(), lambda d:d['grades'].append(d['grades'][0]), lambda d:d['grades'][0]['reference_checks'].pop(),lambda d:d['grades'][0]['citation_checks'][0].update(judgment='guess')):
            data=copy.deepcopy(valid); mutate(data); path.write_text(json.dumps(data))
            with self.assertRaises(ValueError): c.grade(packet,path)
        path.write_text(json.dumps(valid)); other = self.grades(packet,'two')
        data=c.read(other); data['grades'][0]['fact_checks'][0]['id']='another'; other.write_text(json.dumps(data))
        with self.assertRaises(ValueError): c.summarize(self.root/'packet/packet.json',self.root/'key.json',[path,other],self.root/'summary.json')

    def test_tampering_and_duplicate_grader(self):
        packet=self.prepare(); path=self.grades(packet,'one')
        with self.assertRaises(ValueError): c.summarize(self.root/'packet/packet.json',self.root/'key.json',[path,path],self.root/'summary.json')
        run=next(r for r in packet['runs'] if r['artifact']); (self.root/'packet'/run['artifact']).write_text('altered')
        with self.assertRaises(ValueError): c.summarize(self.root/'packet/packet.json',self.root/'key.json',[path,path],self.root/'summary.json')

    def test_invalid_measurement_and_unbalanced_attempts(self):
        self.manifest['runs'][0]['observed_cost']=-1
        with self.assertRaises(ValueError): self.prepare()
        (self.root/'manifest.json').unlink(); self.manifest['runs'][0]['observed_cost']=0; self.manifest['runs'].pop()
        with self.assertRaises(ValueError): self.prepare()

    def test_real_study_cannot_use_synthetic_grader(self):
        packet=self.prepare(); path=self.grades(packet,'one'); data=c.read(path)
        packet['synthetic']=False; data['synthetic']=False; path.write_text(json.dumps(data))
        with self.assertRaises(ValueError): c.grade(packet,path)

    def test_failed_only_study_retains_denominator_and_no_quality_scores(self):
        for run in self.manifest['runs']:
            run.update(status='failed', artifact=None, sanitized_reviewed=False, failure_reason='Synthetic failure')
        packet=self.prepare(); paths=[self.grades(packet,n) for n in ('one','two')]
        result=c.summarize(self.root/'packet/packet.json',self.root/'key.json',paths,self.root/'summary.json')
        self.assertTrue(all(p['completion_rate']==0 for p in result['platforms']))
        self.assertTrue(all(p['human_sample_totals'][0]['fact_checks']['rate_of_error'] is None for p in result['platforms']))

    def test_key_inside_packet_refused_before_creation(self):
        c.write(self.root/'manifest.json',self.manifest)
        with self.assertRaises(ValueError): c.prepare(self.root/'manifest.json',self.root/'packet',self.root/'packet/key.json')
        self.assertFalse((self.root/'packet').exists())

    def test_disagreement_is_retained_without_majority_truth(self):
        packet=self.prepare(); one=self.grades(packet,'one'); two=self.grades(packet,'two')
        data=c.read(two); data['grades'][0]['citation_checks'][0]['judgment']='partial'; two.write_text(json.dumps(data))
        result=c.summarize(self.root/'packet/packet.json',self.root/'key.json',[one,two],self.root/'summary.json')
        row=next(r for r in result['runs'] if r['blind_id']==data['grades'][0]['blind_id'])
        self.assertEqual(row['agreement']['citation_checks'],{'unanimous':0,'items':1})
        self.assertEqual(row['human_judgments'][0]['citation_checks']['supported'],1)
        self.assertEqual(row['human_judgments'][1]['citation_checks']['partial'],1)

    def test_invalid_reference_url_refused_before_packet_creation(self):
        for value in ('not-a-url', 'file:///private/reference', 'https://name:secret@example.org/'):
            self.manifest['reference']['evidence'][0]['source']=value
            manifest_path=self.root/'manifest.json'
            manifest_path.write_text(json.dumps(self.manifest))
            with self.assertRaises(ValueError): c.prepare(manifest_path,self.root/'packet',self.root/'key.json')
            self.assertFalse((self.root/'packet').exists())

    def sample_registry(self):
        rows = []
        for run in self.manifest['runs']:
            if run['status'] != 'completed': continue
            rows.append({**{k: run[k] for k in ('platform', 'case_id', 'replicate')},
                         'citation_checks': [{'id':'claim-1', 'location':'paragraph 1 sentence 1', 'statement':'Safe means read-only semantics.'}],
                         'fact_checks': [{'id':'claim-1', 'location':'paragraph 1 sentence 1', 'statement':'Safe means read-only semantics.'}]})
        path = self.root/'samples.json'; c.write(path, rows); return path

    def test_real_study_requires_frozen_sample_descriptions(self):
        self.manifest['synthetic'] = False
        c.write(self.root/'manifest.json', self.manifest)
        with self.assertRaisesRegex(ValueError, 'sample registry'):
            c.prepare(self.root/'manifest.json', self.root/'packet', self.root/'key.json')
        self.assertFalse((self.root/'packet').exists())
        samples = self.sample_registry()
        c.prepare(self.root/'manifest.json', self.root/'packet', self.root/'key.json', samples)
        packet = c.read(self.root/'packet/packet.json')
        self.assertEqual(len(packet['samples']), 2)
        self.assertNotIn('fixture-a', json.dumps(packet))
        template = c.read(self.root/'packet/grade-template.json')
        self.assertEqual(template['grades'][0]['citation_checks'][0]['id'], 'claim-1')
        self.assertIn('REPLACE', template['grades'][0]['citation_checks'][0]['reason'])

    def test_frozen_samples_reject_relabeling_and_unbalanced_registry(self):
        samples = self.sample_registry()
        c.write(self.root/'manifest.json', self.manifest)
        c.prepare(self.root/'manifest.json', self.root/'packet', self.root/'key.json', samples)
        packet = c.read(self.root/'packet/packet.json'); path = self.grades(packet,'one')
        data = c.read(path); data['grades'][0]['fact_checks'][0]['id']='swapped-claim'
        path.write_text(json.dumps(data))
        with self.assertRaisesRegex(ValueError, 'frozen'):
            c.grade(packet,path)
        registry=c.read(samples); registry[0]['fact_checks'].append({'id':'extra', 'location':'paragraph 2', 'statement':'Additional claim'})
        samples.write_text(json.dumps(registry))
        with self.assertRaisesRegex(ValueError, 'same sample counts'):
            c.prepare(self.root/'manifest.json',self.root/'other-packet',self.root/'other-key.json',samples)
        self.assertFalse((self.root/'other-packet').exists())

    def test_readiness_refuses_synthetic_and_reports_measurement_gaps(self):
        packet=self.prepare(); paths=[self.grades(packet,n) for n in ('one','two')]
        summary=c.summarize(self.root/'packet/packet.json',self.root/'key.json',paths,None)
        gate=c.readiness(summary)
        self.assertFalse(gate['ready_for_descriptive_review'])
        self.assertFalse(gate['cost_comparison_ready'])
        self.assertFalse(gate['timing_comparison_ready'])
        self.assertTrue(any('synthetic' in item for item in gate['missing']))
        self.assertTrue(any('10 distinct cases' in item for item in gate['missing']))
        self.assertFalse(gate['superiority_established'])

    def test_readiness_complete_descriptive_study_keeps_unknown_cost_separate(self):
        # Synthetic in-memory structural fixture, never a study result.
        rows=[]
        for platform in ('one','two'):
            for case in range(10):
                for replicate in (1,2):
                    rows.append({'platform':platform,'case_id':str(case),'replicate':replicate,'status':'completed',
                                 'elapsed_seconds':1,'observed_cost':0,'currency':'USD',
                                 'human_judgments':[{'citation_checks':{'checked':5},'fact_checks':{'checked':5}}]})
        summary={'study_id':'gate-unit-fixture','synthetic':False,'sampling_frozen':True,'runs':rows}
        gate=c.readiness(summary)
        self.assertTrue(gate['ready_for_descriptive_review'])
        self.assertTrue(gate['timing_comparison_ready'])
        self.assertTrue(gate['cost_comparison_ready'])
        rows[0]['observed_cost']=None
        self.assertTrue(c.readiness(summary)['ready_for_descriptive_review'])
        self.assertFalse(c.readiness(summary)['cost_comparison_ready'])
        rows[0]['observed_cost']=0; rows[0]['currency']='EUR'
        self.assertFalse(c.readiness(summary)['cost_comparison_ready'])
        self.assertFalse(c.readiness(summary)['superiority_established'])

    def test_duplicate_json_keys(self):
        path=self.root/'bad.json'; path.write_text('{"x":1,"x":2}')
        with self.assertRaises(ValueError): c.read(path)

if __name__=='__main__': unittest.main()
